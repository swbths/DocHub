        /// <summary>返回指定语言的语录池；未知语言回退到简体中文。</summary>
        public static IReadOnlyList<Quote> For(Language language)
        {
            return Pools.TryGetValue(language, out Quote[]? pool) ? pool : Pools[Language.ZhCn];
        }

        public static Quote At(Language language, int index)
        {
            IReadOnlyList<Quote> pool = For(language);
            if (pool.Count == 0) return new Quote(string.Empty, string.Empty);
            return pool[((index % pool.Count) + pool.Count) % pool.Count];
        }

        /// <summary>随机抽取下一句的下标；previousIndex 有效时避免与上一句重复。</summary>
        public static int NextRandomIndex(Language language, int previousIndex)
        {
            int count = For(language).Count;
            if (count == 0) return -1;
            if (count == 1) return 0;

            int next = Random.Shared.Next(count - 1);
            if (previousIndex >= 0 && next >= previousIndex) next++;
            return next;
        }
